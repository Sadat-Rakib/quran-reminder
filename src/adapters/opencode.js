'use strict';

const fs = require('fs');
const path = require('path');
const fsutil = require('../core/fsutil');
const { result, note, projectPath, userPath } = require('./util');

const id = 'opencode';

function pluginSource(ctx) {
  const node = JSON.stringify(String(ctx.nodePath).replace(/\\/g, '/'));
  const cli = JSON.stringify(path.join(ctx.appRoot, 'bin', 'quran.js').replace(/\\/g, '/'));
  return `// quran-reminder — generated by \`quran install opencode\`
// Safe to delete. Regenerate with: quran install opencode
import { execFile } from "node:child_process"
import { promisify } from "node:util"

const execFileAsync = promisify(execFile)
const NODE = ${node}
const CLI = ${cli}

export const QuranReminder = async ({ client, directory }) => {
  const seen = new Set()

  return {
    event: async ({ event }) => {
      if (!event || event.type !== "session.created") return
      const id =
        event.properties?.info?.id ||
        event.properties?.sessionID ||
        event.properties?.session?.id
      if (!id || seen.has(id)) return
      seen.add(id)

      try {
        const { stdout } = await execFileAsync(
          NODE,
          [CLI, "hook", "--host", "opencode"],
          {
            cwd: directory,
            timeout: 5000,
            env: { ...process.env, QURAN_REMINDER_SESSION_ID: id, QURAN_REMINDER_PROJECT: directory },
          }
        )
        const payload = JSON.parse(stdout || "{}")
        const text = payload.user_message || payload.systemMessage
        if (!text) return
        await client.session.prompt({
          path: { id },
          body: { noReply: true, parts: [{ type: "text", text }] },
        })
      } catch (_) {
        // Never break the user's session.
      }
    },
  }
}
`;
}

module.exports = {
  id,
  name: 'OpenCode',
  kind: 'plugin',
  defaultScope: 'project',
  scopes: ['user', 'project'],
  docs: 'https://opencode.ai/docs/plugins/',
  capability: 'Local plugin — injects the verse into each new session without triggering a reply.',

  file(ctx) {
    return ctx.scope === 'project'
      ? projectPath(ctx, '.opencode', 'plugins', 'quran-reminder.js')
      : userPath(ctx, '.config', 'opencode', 'plugins', 'quran-reminder.js');
  },

  detect(ctx) {
    return (
      fsutil.exists(projectPath(ctx, '.opencode')) ||
      fsutil.exists(userPath(ctx, '.config', 'opencode')) ||
      fsutil.exists(userPath(ctx, '.opencode'))
    );
  },

  install(ctx) {
    const res = result();
    const file = this.file(ctx);
    const source = pluginSource(ctx);
    const current = fsutil.readText(file);
    if (current === source) {
      res.unchanged.push(file);
      return res;
    }
    if (current !== null) {
      const saved = fsutil.backup(file);
      if (saved) res.notes.push(`Backup written to ${saved}`);
    }
    fsutil.writeText(file, source);
    res.changed.push(file);
    note(res, 'OpenCode loads plugins from this directory at startup — restart OpenCode once.');
    return res;
  },

  uninstall(ctx) {
    const res = result();
    const file = this.file(ctx);
    if (!fsutil.exists(file)) {
      res.unchanged.push(file);
      return res;
    }
    try {
      fs.unlinkSync(file);
      res.changed.push(file);
    } catch (error) {
      res.ok = false;
      res.errors.push(error.message);
    }
    return res;
  },

  verify(ctx) {
    const file = this.file(ctx);
    const content = fsutil.readText(file);
    if (content === null) return { installed: false, ok: false, detail: 'plugin file not found' };
    const ok = content.includes('quran-reminder') && content.includes('session.created');
    return ok
      ? { installed: true, ok: true, detail: `plugin at ${file}` }
      : { installed: false, ok: false, detail: 'plugin file does not look like ours' };
  },
};
